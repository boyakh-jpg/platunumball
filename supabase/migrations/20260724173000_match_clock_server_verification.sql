create table if not exists public.match_clock_sessions (
  match_id text primary key references public.matches(id) on delete cascade,
  controller_id text,
  status text not null default 'pending',
  current_period smallint not null default 1,
  overtime_count smallint not null default 0,
  period_remaining_ms bigint not null default 0,
  shot_clock_seconds smallint not null default 0,
  shot_remaining_ms bigint not null default 0,
  active_elapsed_ms bigint not null default 0,
  last_resumed_at timestamptz,
  start_deadline_at timestamptz not null,
  clock_started_at timestamptz,
  clock_ended_at timestamptz,
  started_within_window boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint match_clock_sessions_status_check
    check (status in ('pending', 'running', 'paused', 'break', 'ended')),
  constraint match_clock_sessions_period_check check (current_period between 1 and 20),
  constraint match_clock_sessions_overtime_check check (overtime_count between 0 and 20),
  constraint match_clock_sessions_shot_clock_check check (shot_clock_seconds in (0, 30, 35, 60)),
  constraint match_clock_sessions_remaining_check
    check (period_remaining_ms >= 0 and shot_remaining_ms >= 0 and active_elapsed_ms >= 0)
);

create table if not exists public.match_clock_events (
  id bigint generated by default as identity primary key,
  match_id text not null references public.matches(id) on delete cascade,
  actor_id text,
  action text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists match_clock_events_match_created_idx
  on public.match_clock_events (match_id, created_at, id);

